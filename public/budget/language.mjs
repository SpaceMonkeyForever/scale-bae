export let locale = "en-GB";
export function setLocale(value) { locale = value === "id-ID" ? "id-ID" : "en-GB"; }
export { preferredLocale } from "./preference.mjs";
export function t(source, values = {}) {
  const text = locale === "id-ID" && Object.hasOwn(indonesia, source) ? indonesia[source] : source;
  return text.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? values[key] : match);
}

// Bind only the original shell. Budget entries and conversation text are rendered separately.
export function bindShell(root) {
  const bindings = [];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const original = node.data;
    const key = Object.hasOwn(indonesia, original) ? original : original.trim();
    if (Object.hasOwn(indonesia, key)) {
      bindings.push(() => { node.data = original.replace(key, () => t(key)); });
    }
  }
  for (const element of root.querySelectorAll("[aria-label], [title]")) {
    for (const attr of ["aria-label","title"]) {
      const key = element.getAttribute(attr);
      if (key && Object.hasOwn(indonesia, key)) bindings.push(() => element.setAttribute(attr, t(key)));
    }
  }
  return () => bindings.forEach(update => update());
}
